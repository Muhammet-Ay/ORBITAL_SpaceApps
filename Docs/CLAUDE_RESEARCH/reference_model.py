"""ORBITAL reference model v2 (Claude, reconciled with Codex's spec). Plain Python, no dependencies.

Single numeric reference for the C++ implementation. All data comes from
PART_CATALOG.json (parts, mission block, reference builds). Port the functions
1:1 and check the C++ against TEST_CASES.md, generated by:  python reference_model.py

Simplified educational model. NOT flight-grade. See ENGINEERING_FORMULAS.md.
"""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = json.load(open(os.path.join(HERE, "PART_CATALOG.json")))
CAT = {p["id"]: p for p in DATA["parts"]}
M = DATA["mission"]
C, A = M["constants"], M["assumptions"]
G0, MU_E, MU_M = C["g0"], C["mu_earth"], C["mu_moon"]
R_E, R_M, A_MOON, SOLAR = C["r_earth_m"], C["r_moon_m"], C["a_moon_m"], C["solar_w_m2"]
ORBITS, GROUND, BUDGET = M["orbits"], M["ground"], M["budget_mcr"]
OBJECTIVES = {k: v["weight"] for k, v in M["objectives"].items()}
B = DATA["reference_builds"]

# Launch is refused while any BLOCK code is present. RISK codes allow launch and
# the mission then fails or degrades at the phase given in FAIL_PHASE.
BLOCK = {"E_UNKNOWN_PART", "E_MISSING_REQUIRED_PART", "E_SOCKET_LIMIT", "E_PROP_OVER_CAPACITY", "E_BUS_OVERLOAD",
         "E_BUS_INSTRUMENT_SLOTS", "E_COMPUTER_INSTRUMENT_LIMIT", "E_ENGINE_COUNT", "E_TWR_LIFTOFF",
         "E_TWR_STAGE2", "E_LV_DELTA_V", "E_FAIRING_MASS", "E_FAIRING_SIZE", "E_BUDGET"}
FAIL_PHASE = {"R_SC_DELTA_V_INSERTION": "insertion", "R_POWER_GENERATION": "eclipse", "R_BATTERY_ECLIPSE": "eclipse"}


def v_circ(mu, r):
    return math.sqrt(mu / r)


def vis_viva(mu, r, a):
    return math.sqrt(mu * (2.0 / r - 1.0 / a))


def period(mu, a):
    return 2.0 * math.pi * math.sqrt(a ** 3 / mu)


def dv_tli():
    r1 = R_E + A["leo_alt_m"]
    a = (r1 + A_MOON) / 2.0
    return vis_viva(MU_E, r1, a) - v_circ(MU_E, r1)


def v_inf_moon():
    r1 = R_E + A["leo_alt_m"]
    a = (r1 + A_MOON) / 2.0
    return v_circ(MU_E, A_MOON) - vis_viva(MU_E, A_MOON, a)


def dv_loi(orbit_id):
    o = ORBITS[orbit_id]
    rp, ra = R_M + o["hp_m"], R_M + o["ha_m"]
    v_hyp = math.sqrt(v_inf_moon() ** 2 + 2.0 * MU_M / rp)
    return v_hyp - vis_viva(MU_M, rp, (rp + ra) / 2.0)


def orbit_period_s(orbit_id):
    o = ORBITS[orbit_id]
    return period(MU_M, R_M + (o["hp_m"] + o["ha_m"]) / 2.0)


def eclipse_fraction(orbit_id):
    o = ORBITS[orbit_id]
    return math.asin(R_M / (R_M + (o["hp_m"] + o["ha_m"]) / 2.0)) / math.pi


def tsiolkovsky(isp, m0, mf):
    if not (m0 > 0 and mf > 0 and m0 >= mf):
        raise ValueError("invalid mass ratio")
    return isp * G0 * math.log(m0 / mf)


def spacecraft(d):
    """d keys: bus, tanks[], engine, prop_kg, adcs[], solar[], battery[], antenna, computer,
    instruments[], orbit, years, ground. Missing single parts may be None."""
    block, risk, warn = [], [], []
    singles = {"probe-core": d.get("bus"), "probe-engine": d.get("engine"), "antenna": d.get("antenna"),
               "avionics": d.get("computer")}
    lists = {"probe-tank": d.get("tanks", []), "adcs": d.get("adcs", []), "solar": d.get("solar", []),
             "battery": d.get("battery", []), "instrument": d.get("instruments", [])}
    ids = [v for v in singles.values() if v] + [i for l in lists.values() for i in l]
    if any(i not in CAT for i in ids) or not math.isfinite(d.get("prop_kg", 0)) or d.get("prop_kg", 0) < 0:
        return dict(block=["E_UNKNOWN_PART"], risk=[], warn=[], wet=0.0, cost=0.0, ops_cost=0.0)
    missing = [s for s in M["required_probe_slots"] if not (singles.get(s) or lists.get(s))]
    if "rcs" not in lists["adcs"] and "adcs" not in missing:
        missing.append("adcs")
    if missing:
        return dict(block=["E_MISSING_REQUIRED_PART"], missing=missing, risk=[], warn=[], wet=0.0, cost=0.0,
                    ops_cost=0.0)
    for s, lim in M["socket_limits"].items():
        if s in lists and len(lists[s]) > lim:
            block.append("E_SOCKET_LIMIT")
            break
    P = [CAT[i] for i in ids]
    bus = CAT[d["bus"]]
    inst = lists["instrument"]
    dry = sum(p["mass_kg"] for p in P)
    cap = sum(CAT[t]["prop_capacity_kg"] for t in lists["probe-tank"])
    prop = d["prop_kg"]
    wet = dry + prop
    cost = sum(p["cost_mcr"] for p in P)
    dv = tsiolkovsky(CAT[d["engine"]]["isp_s"], wet, dry)
    o = ORBITS[d["orbit"]]
    m = 1 + A["dv_margin"]
    dv_fixed = A["dv_mcc_mps"] + dv_loi(d["orbit"])
    dv_req = (dv_fixed + o["sk_mps_per_year"] * d["years"]) * m
    years_possible = max(0.0, (dv / m - dv_fixed) / o["sk_mps_per_year"])
    inserted = dv / m >= dv_fixed
    life_frac = min(1.0, years_possible / d["years"]) if inserted else 0.0
    load = bus["base_power_w"] + sum(p.get("power_w", 0) for p in P if p is not bus)
    gen = sum(CAT[s]["area_m2"] for s in lists["solar"]) * SOLAR * A["cell_eff"] * A["point_loss"]
    T = orbit_period_s(d["orbit"])
    fe = eclipse_fraction(d["orbit"])
    t_ecl, t_sun = fe * T, (1 - fe) * T
    e_ecl_wh = load * t_ecl / 3600.0
    batt_usable = sum(CAT[b]["capacity_wh"] for b in lists["battery"]) * A["dod"]
    gen_needed = load + e_ecl_wh * 3600.0 / (t_sun * A["chg_eff"])
    fine = "reaction_wheels" in lists["adcs"]
    working = [i for i in inst if fine or not CAT[i].get("needs_fine_pointing")]
    antenna_ok = fine or not CAT[d["antenna"]].get("needs_fine_pointing")
    gen_gb = sum(CAT[i]["data_gb_per_day"] for i in working)
    g = GROUND[d["ground"]]
    contact_s = g["hours"] * 3600.0 * A["orbit_visible"]
    down_gb = CAT[d["antenna"]]["data_rate_mbps"] * 1e6 * contact_s / 8.0 / 1e9 if antenna_ok else 0.0
    storage = CAT[d["computer"]]["storage_gb"]
    storage_need = gen_gb * g["max_gap_h"] / 24.0
    stored_frac = 1.0 if storage_need <= storage else storage / storage_need
    data_frac = 1.0 if gen_gb == 0 else min(1.0, stored_frac, down_gb / gen_gb)
    if prop > cap + 1e-9:
        block.append("E_PROP_OVER_CAPACITY")
    if wet > bus["max_wet_mass_kg"]:
        block.append("E_BUS_OVERLOAD")
    if len(inst) > bus["max_instruments"]:
        block.append("E_BUS_INSTRUMENT_SLOTS")
    if len(inst) > CAT[d["computer"]]["max_instruments"]:
        block.append("E_COMPUTER_INSTRUMENT_LIMIT")
    if not inst:
        risk.append("R_NO_INSTRUMENT")
    if len(working) < len(inst) or not antenna_ok:
        risk.append("R_NEEDS_FINE_POINTING")
    if not inserted:
        risk.append("R_SC_DELTA_V_INSERTION")
    elif dv < dv_req:
        risk.append("R_SC_DELTA_V_LIFETIME")
    if gen < gen_needed:
        risk.append("R_POWER_GENERATION")
    if batt_usable < e_ecl_wh:
        risk.append("R_BATTERY_ECLIPSE")
    if storage < storage_need:
        risk.append("R_STORAGE")
    if data_frac < 1.0 and gen_gb > 0:
        warn.append("W_DATA_BOTTLENECK")
    ops_cost = (A["ops_base_cost_per_year"] + g["cost_per_year"]) * d["years"]
    return dict(dry=dry, prop=prop, wet=wet, cost=cost, ops_cost=ops_cost, dv=dv, dv_req=dv_req, dv_fixed=dv_fixed,
                years_possible=years_possible, life_frac=life_frac, load=load, gen=gen, gen_needed=gen_needed,
                e_ecl_wh=e_ecl_wh, batt_usable=batt_usable, period_min=T / 60, eclipse_min=t_ecl / 60,
                gen_gb=gen_gb, down_gb=down_gb, data_frac=data_frac, storage_need=storage_need, storage=storage,
                working=working, block=block, risk=risk, warn=warn)


def launcher(lv, payload_kg, bus_id):
    """lv keys: s1_tank, s1_engine, s1_count, s2_tank, s2_engine, fairing."""
    keys = ["s1_tank", "s1_engine", "s2_tank", "s2_engine", "fairing"]
    if any(not lv.get(k) for k in keys):
        return dict(block=["E_MISSING_REQUIRED_PART"], cost=0.0)
    if any(lv[k] not in CAT for k in keys):
        return dict(block=["E_UNKNOWN_PART"], cost=0.0)
    t1, e1, n = CAT[lv["s1_tank"]], CAT[lv["s1_engine"]], lv["s1_count"]
    t2, e2, f = CAT[lv["s2_tank"]], CAT[lv["s2_engine"]], CAT[lv["fairing"]]
    sep = CAT["sep_system"]
    block = []
    if n < 1 or n > e1["max_count"]:
        return dict(block=["E_ENGINE_COUNT"], cost=0.0)
    s2_dry = t2["mass_kg"] + e2["mass_kg"] + sep["mass_kg"]
    s1_dry = t1["mass_kg"] + n * e1["mass_kg"] + sep["mass_kg"]
    s1_prop, s2_prop = t1["prop_capacity_kg"], t2["prop_capacity_kg"]
    m2_0 = s2_dry + s2_prop + payload_kg
    m1_0 = s1_dry + s1_prop + f["mass_kg"] + m2_0
    isp1 = (e1["isp_sl_s"] + e1["isp_vac_s"]) / 2.0
    dv1 = tsiolkovsky(isp1, m1_0, m1_0 - s1_prop)
    dv2 = tsiolkovsky(e2["isp_vac_s"], m2_0, m2_0 - s2_prop)
    dv_req = A["dv_ascent_mps"] + dv_tli()
    twr1 = n * e1["thrust_sl_n"] / (m1_0 * G0)
    twr2 = e2["thrust_vac_n"] / (m2_0 * G0)
    cost = (t1["cost_mcr"] + n * e1["cost_mcr"] + t2["cost_mcr"] + e2["cost_mcr"] + f["cost_mcr"]
            + 2 * sep["cost_mcr"])
    if twr1 < A["min_twr_liftoff"]:
        block.append("E_TWR_LIFTOFF")
    if twr2 < A["min_twr_stage2"]:
        block.append("E_TWR_STAGE2")
    if dv1 + dv2 < dv_req:
        block.append("E_LV_DELTA_V")
    if payload_kg > f["max_payload_kg"]:
        block.append("E_FAIRING_MASS")
    if bus_id not in f["fits_bus"]:
        block.append("E_FAIRING_SIZE")
    t1_burn = s1_prop / (n * e1["thrust_sl_n"] / (isp1 * G0))
    mdot2 = e2["thrust_vac_n"] / (e2["isp_vac_s"] * G0)
    t2_burn = s2_prop / mdot2

    def t_after_s2_ignition(dv_target):
        """Seconds of stage 2 burn needed to add dv_target; None if the stage cannot."""
        if dv_target <= 0:
            return 0.0
        used = m2_0 * (1.0 - math.exp(-dv_target / (e2["isp_vac_s"] * G0)))
        return used / mdot2 if used <= s2_prop + 1e-9 else None

    t_parking = t_after_s2_ignition(A["dv_ascent_mps"] - dv1)
    t_tli = t_after_s2_ignition(dv_req - dv1)
    return dict(liftoff_mass=m1_0, dv1=dv1, dv2=dv2, dv_total=dv1 + dv2, dv_req=dv_req, twr1=twr1, twr2=twr2,
                cost=cost, t1_burn=t1_burn, t2_burn=t2_burn, t_parking=t_parking, t_tli=t_tli, block=block)


def evaluate(sc_design, lv_design, primary, difficulty="normal"):
    sc = spacecraft(sc_design)
    lv = launcher(lv_design, sc["wet"], sc_design.get("bus"))
    total_cost = sc["cost"] + sc["ops_cost"] + lv["cost"]
    budget = BUDGET[difficulty]
    block = sc["block"] + lv["block"]
    if total_cost > budget:
        block.append("E_BUDGET")
    risk, warn = list(sc["risk"]), list(sc["warn"])
    res = dict(sc=sc, lv=lv, total_cost=total_cost, budget=budget, block=block, risk=risk, warn=warn,
               launch_allowed=not block, fail_phase=None, science=0.0, per_objective={}, primary_ok=False,
               success=False, score=0.0)
    if block:
        return res
    have = {CAT[i]["objective"] for i in sc["working"]}
    if primary not in have:
        risk.append("R_PRIMARY_INSTRUMENT_MISSING")
    fatal = [r for r in risk if r in FAIL_PHASE]
    if fatal:
        res["fail_phase"] = FAIL_PHASE[fatal[0]]     # insertion is checked before eclipse
        return res
    o = ORBITS[sc_design["orbit"]]
    per = {ob: (w * o["factor"][ob] * sc["data_frac"] * sc["life_frac"] if ob in have else 0.0)
           for ob, w in OBJECTIVES.items()}
    science = sum(per.values())
    primary_ok = per.get(primary, 0.0) >= A["primary_pass"] * OBJECTIVES[primary]
    res.update(per_objective=per, science=science, primary_ok=primary_ok, success=primary_ok,
               score=0.8 * science + (20.0 * max(0.0, 1 - total_cost / budget) if primary_ok else 0.0))
    return res


def variant(base, **kw):
    d = dict(base)
    d.update(kw)
    return d


