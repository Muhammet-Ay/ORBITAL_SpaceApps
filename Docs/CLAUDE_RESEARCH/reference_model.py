def boundary_checks():
    out = []
    r = evaluate(SS, LM, "O1_ICE")
    BUDGET["_t"] = r["total_cost"]
    out.append(("Budget equal to cost passes", "E_BUDGET" not in evaluate(SS, LM, "O1_ICE", "_t")["block"]))
    BUDGET["_t"] = r["total_cost"] - 0.01
    out.append(("Budget 0.01 below cost blocks", "E_BUDGET" in evaluate(SS, LM, "O1_ICE", "_t")["block"]))
    del BUDGET["_t"]
    out.append(("Payload equal to fairing limit passes",
                "E_FAIRING_MASS" not in launcher(LL, CAT["fairing_s"]["max_payload_kg"], "bus_small")["block"]))
    out.append(("Payload 0.1 kg above fairing limit blocks",
                "E_FAIRING_MASS" in launcher(LL, CAT["fairing_s"]["max_payload_kg"] + 0.1, "bus_small")["block"]))
    a, b = evaluate(SS, LM, "O1_ICE"), evaluate(SS, LM, "O1_ICE")
    out.append(("Same design evaluated twice gives identical results", a == b))
    out.append(("Unknown part id is rejected",
                spacecraft(variant(SP, antenna="does_not_exist"))["block"] == ["E_UNKNOWN_PART"]))
    return out


def main():
    print("== Constants check ==")
    print(f"LEO circular speed (200 km): {v_circ(MU_E, R_E + A['leo_alt_m']):.1f} m/s")
    print(f"TLI delta-v: {dv_tli():.1f} m/s")
    print(f"Arrival v_inf at Moon: {v_inf_moon():.1f} m/s")
    for k in ORBITS:
        print(f"{k}: LOI {dv_loi(k):.1f} m/s, period {orbit_period_s(k)/60:.1f} min, "
              f"eclipse {eclipse_fraction(k)*orbit_period_s(k)/60:.1f} min")
    print(f"Launch vehicle requirement: {A['dv_ascent_mps'] + dv_tli():.1f} m/s")
    for name, setup, sc, lv, prim, diff in CASES:
        r = evaluate(sc, lv, prim, diff)
        s, l = r["sc"], r["lv"]
        print(f"\n== {name} ==")
        print(f"Setup: {setup}")
        if "dry" in s:
            print(f"SC dry {s['dry']:.1f} kg, wet {s['wet']:.1f} kg, dv {s['dv']:.1f} / req {s['dv_req']:.1f} m/s, "
                  f"years possible {s['years_possible']:.2f}")
            print(f"Power load {s['load']:.0f} W, gen {s['gen']:.0f} W / need {s['gen_needed']:.0f} W, "
                  f"eclipse {s['e_ecl_wh']:.0f} Wh / usable {s['batt_usable']:.0f} Wh")
            print(f"Data gen {s['gen_gb']:.2f} GB/day, downlink {s['down_gb']:.3f} GB/day, fraction "
                  f"{s['data_frac']:.3f}, storage need {s['storage_need']:.2f} / {s['storage']} GB")
        if "dv_total" in l:
            print(f"LV liftoff {l['liftoff_mass']:.0f} kg, dv {l['dv_total']:.1f} / req {l['dv_req']:.1f} m/s "
                  f"(S1 {l['dv1']:.1f}, S2 {l['dv2']:.1f}), TWR {l['twr1']:.3f} / {l['twr2']:.3f}, "
                  f"burn {l['t1_burn']:.0f} s / {l['t2_burn']:.0f} s")
            fmt = lambda v: "not reached" if v is None else f"{v:.0f} s"
            print(f"Events after stage 2 ignition: parking orbit {fmt(l['t_parking'])}, TLI complete {fmt(l['t_tli'])}")
        print(f"Cost {r['total_cost']:.1f} / budget {r['budget']:.0f} M credits ({diff})")
        print(f"BLOCK {r['block']}  RISK {r['risk']}  WARN {r['warn']}")
        print(f"Launch allowed {r['launch_allowed']}, fail phase {r['fail_phase']}, science {r['science']:.1f}, "
              f"primary_ok {r['primary_ok']}, success {r['success']}, score {r['score']:.1f}")
    print("\n== Boundary and determinism checks ==")
    for label, ok in boundary_checks():
        print(f"{'PASS' if ok else 'FAIL'}  {label}")


if __name__ == "__main__":
    main()
